// 挨拶文を作るための指示文と、結果の取り出し（純粋な関数。テストで確かめる）

/** 'YYYY-MM-DD' → '11月6日' */
export function japaneseDate(date: string): string {
  return `${Number(date.slice(5, 7))}月${Number(date.slice(8, 10))}日`;
}

